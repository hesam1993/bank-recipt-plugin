<?php
namespace C2CReceipts;

defined( 'ABSPATH' ) || exit;

final class Http {
	public static function register(): void {
		foreach ( array( 'boot', 'upload', 'replace', 'status' ) as $action ) {
			add_action( 'wc_ajax_c2c_' . $action, static function () use ( $action ) {
				self::endpoint( $action );
			} );
		}
		add_action( 'admin_post_c2c_file', array( self::class, 'file' ) );
		add_action( 'admin_post_nopriv_c2c_file', array( self::class, 'file' ) );
	}

	private static function same_origin(): void {
		if ( 'POST' !== Support::request_method() ) {
			throw new \RuntimeException( esc_html( __( 'POST requests are required.', 'c2c-receipts' ) ) );
		}
		$source = sanitize_url( Support::server( 'HTTP_ORIGIN' ) ?: Support::server( 'HTTP_REFERER' ) );
		$origin = static function ( string $url ): string {
			$parts = wp_parse_url( $url );
			if ( ! is_array( $parts ) || empty( $parts['scheme'] ) || empty( $parts['host'] ) ) {
				return '';
			}
			$scheme = strtolower( $parts['scheme'] );
			return $scheme . '://' . strtolower( $parts['host'] ) . ':' . ( $parts['port'] ?? ( 'https' === $scheme ? 443 : 80 ) );
		};
		if ( '' === $source || ! in_array( $origin( $source ), array( $origin( home_url() ), $origin( site_url() ) ), true ) ) {
			throw new \RuntimeException( esc_html( __( 'The request origin could not be verified. Reload checkout.', 'c2c-receipts' ) ) );
		}
	}

	private static function endpoint( string $action ): void {
		nocache_headers();
		header( 'Cache-Control: no-store, private, max-age=0' );
		try {
			self::same_origin();
			$owner = Support::owner();
			if ( 'boot' === $action ) {
				wp_send_json_success( array( 'nonce' => wp_create_nonce( 'c2c_upload_' . $owner ) ) );
			}
			if ( ! wp_verify_nonce( Support::post( 'nonce' ), 'c2c_upload_' . $owner ) ) {
				wp_send_json_error( array( 'message' => __( 'Your upload session expired. Reload this page; do not transfer again.', 'c2c-receipts' ) ), 403 );
			}
			$order_id = absint( Support::post( 'order_id' ) );
			$order = $order_id ? wc_get_order( $order_id ) : null;
			if ( $order_id && ( ! $order || ! Customer::allowed( $order, Support::access_input( true ) ) ) ) {
				wp_send_json_error( array( 'message' => __( 'This order link is invalid or expired.', 'c2c-receipts' ) ), 403 );
			}
			if ( 'status' === $action ) {
				$row = Receipts::validate( Support::post( 'token' ) );
				wp_send_json_success( array( 'amount' => Support::amount( $row->amount, $row->currency ), 'account' => json_decode( $row->account, true ), 'state' => $row->state ) );
			}
			if ( 'upload' === $action ) {
				if ( $order ) {
					$row = Receipts::get( (int) $order->get_meta( '_c2c_receipt_id' ) );
					if ( ! $row || 'rejected' !== $row->state || ! $order->has_status( 'on-hold' ) || 'c2c_receipts' !== $order->get_payment_method() ) {
						throw new \RuntimeException( esc_html( __( 'This order cannot accept a replacement receipt.', 'c2c-receipts' ) ) );
					}
				} else {
					$gateways = WC()->payment_gateways()->get_available_payment_gateways();
					if ( ! isset( $gateways['c2c_receipts'] ) ) {
						throw new \RuntimeException( esc_html( __( 'Card to card is currently unavailable.', 'c2c-receipts' ) ) );
					}
				}
				if ( ! isset( $_FILES['receipt']['name'], $_FILES['receipt']['tmp_name'], $_FILES['receipt']['error'], $_FILES['receipt']['size'] ) || ! is_string( $_FILES['receipt']['name'] ) || ! is_string( $_FILES['receipt']['tmp_name'] ) || ! is_int( $_FILES['receipt']['error'] ) || ! is_int( $_FILES['receipt']['size'] ) ) {
					throw new \RuntimeException( esc_html__( 'Choose one receipt image.', 'c2c-receipts' ) );
				}
				// $_FILES is generated by PHP and is not WordPress-magic-quoted. Never strip slashes from its temporary filesystem path.
				// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- Server-generated temporary path; is_uploaded_file below verifies provenance before any file operation.
				$tmp = $_FILES['receipt']['tmp_name'];
				if ( ! is_uploaded_file( $tmp ) ) {
					throw new \RuntimeException( esc_html__( 'Choose one receipt image.', 'c2c-receipts' ) );
				}
				$file = array(
					'name' => sanitize_file_name( $_FILES['receipt']['name'] ),
					'tmp_name' => $tmp,
					'error' => absint( $_FILES['receipt']['error'] ),
					'size' => absint( $_FILES['receipt']['size'] ),
				);
				wp_send_json_success( Receipts::stage( $file, Support::post( 'account' ), Support::post( 'reference' ), $order ) );
			}
			if ( ! $order ) {
				throw new \RuntimeException( esc_html( __( 'Order not found.', 'c2c-receipts' ) ) );
			}
			Receipts::attach( $order, Support::post( 'token' ), true );
			wp_send_json_success( array( 'message' => __( 'Receipt received; payment awaiting verification.', 'c2c-receipts' ) ) );
		} catch ( \Throwable $e ) {
			wp_send_json_error( array( 'message' => $e instanceof \RuntimeException || $e instanceof \InvalidArgumentException ? Support::plain_error( $e ) : __( 'The receipt request could not be completed. Please contact the store; do not transfer again.', 'c2c-receipts' ) ), 400 );
		}
	}


	public static function file_url( object $row, array $access = array() ): string {
		return add_query_arg( array_merge( $access, array( 'action' => 'c2c_file', 'receipt_id' => $row->id ) ), admin_url( 'admin-post.php' ) );
	}

	public static function file(): void {
		$id = absint( Support::get( 'receipt_id' ) );
		$row = Receipts::get( $id );
		$order = $row && $row->order_id ? wc_get_order( $row->order_id ) : null;
		if ( ! $row || ! $order || ! Customer::allowed( $order, Support::access_input() ) || '' === $row->filename ) {
			wp_die( esc_html__( 'Receipt unavailable or access denied.', 'c2c-receipts' ), '', array( 'response' => 403 ) );
		}
		try {
			$bytes = Storage::read( $row->filename );
			nocache_headers();
			header( 'Cache-Control: private, no-store, max-age=0' );
			header( 'Content-Type: image/jpeg' );
			header( 'Content-Disposition: inline; filename="receipt-' . $id . '.jpg"' );
			header( 'X-Content-Type-Options: nosniff' );
			header( "Content-Security-Policy: default-src 'none'; frame-ancestors 'self'" );
			header( 'Referrer-Policy: no-referrer' );
			// Binary bytes are an authenticated JPEG, not HTML. Never escape or log image data.
			echo $bytes; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
			exit;
		} catch ( \Throwable $e ) {
			wp_die( esc_html__( 'Receipt unavailable.', 'c2c-receipts' ), '', array( 'response' => 404 ) );
		}
	}
}
